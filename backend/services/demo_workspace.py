from __future__ import annotations

import json
import os
from datetime import datetime, timedelta

from sqlalchemy.orm import Session

from ..models import (
    ActivityEvent,
    Approval,
    Asset,
    Audit,
    AuditFinding,
    BrandGuideline,
    ConsistencyReport,
    VideoReview,
)
from .asset_service import get_upload_directory
from .consistency_service import build_consistency_report


_DEMO_CAMPAIGN_NAMES = (
    '[DEMO SAMPLE] Spring launch email',
    '[DEMO SAMPLE] Product launch landing page',
)


def seed_demo_workspace(db: Session, uid: str, email: str | None) -> None:
    configured_email = os.getenv('DEMO_ACCOUNT_EMAIL', '').strip().casefold()
    if not configured_email or not email or email.strip().casefold() != configured_email:
        return

    seeded = db.query(Audit.id).filter(
        Audit.user_id == uid,
        Audit.campaign_name == _DEMO_CAMPAIGN_NAMES[0],
    ).first()
    if seeded:
        return

    guideline = db.query(BrandGuideline).filter(
        BrandGuideline.user_id == uid,
        BrandGuideline.rule_name == 'Prohibited phrase',
    ).order_by(BrandGuideline.id.asc()).first()
    if not guideline:
        raise RuntimeError('The demo workspace requires its default prohibited-phrase guideline.')

    now = datetime.utcnow()
    audits = [
        Audit(
            campaign_name=name,
            campaign_type=campaign_type,
            submitted_content=content,
            risk_score=risk_score,
            risk_category='high',
            audit_status='completed',
            analysis_mode='rules_only',
            created_at=now - timedelta(days=offset),
            user_id=uid,
        )
        for name, campaign_type, content, risk_score, offset in (
            (
                _DEMO_CAMPAIGN_NAMES[0],
                'Email',
                'DEMO SAMPLE ONLY: Guaranteed results with our spring launch.',
                45,
                3,
            ),
            (
                _DEMO_CAMPAIGN_NAMES[1],
                'Website',
                'DEMO SAMPLE ONLY: Our product guarantees results for every campaign.',
                35,
                1,
            ),
        )
    ]
    db.add_all(audits)
    db.flush()

    for audit, evidence in zip(
        audits,
        ('Guaranteed results', 'guarantees results'),
        strict=True,
    ):
        db.add(AuditFinding(
            audit_id=audit.id,
            finding_title='Demonstration: prohibited guarantee language',
            severity='high',
            evidence_text=evidence,
            explanation='Illustrative rule-based sample finding; this record was not generated by an AI model.',
            related_guideline_id=guideline.id,
            suggested_correction='Replace this demonstration claim with substantiated, factual language.',
            finding_status='confirmed',
            user_id=uid,
        ))
        db.add(Approval(
            audit_id=audit.id,
            decision='pending' if audit is audits[0] else 'approved',
            reviewer='Demo workspace sample',
            comment='Demonstration approval record; not a real campaign decision.',
            decision_timestamp=audit.created_at,
            user_id=uid,
        ))
        db.add(ActivityEvent(
            event_type='Demo sample campaign audit',
            description=f'Demonstration-only audit sample: {audit.campaign_name}',
            related_entity_id=str(audit.id),
            timestamp=audit.created_at,
            user_id=uid,
        ))

    upload_directory = get_upload_directory()
    db.add(Asset(
        original_filename='[DEMO SAMPLE - metadata only] Spring campaign creative.png',
        stored_filename='demo-sample-metadata-only.png',
        mime_type='image/png',
        file_size=0,
        campaign_name=_DEMO_CAMPAIGN_NAMES[0],
        tags=json.dumps(['demo sample', 'metadata only', 'spring']),
        extracted_text='Demonstration metadata only. No uploaded file is stored.',
        uploaded_at=now - timedelta(days=2),
        review_status='approved',
        file_path=str(upload_directory / 'demo-sample-metadata-only.png'),
        user_id=uid,
    ))

    db.add(VideoReview(
        original_filename='[DEMO SAMPLE - illustrative only] Brand launch video.mp4',
        duration_seconds=24.0,
        frame_count=3,
        risk_score=20,
        risk_category='medium',
        compliance_score=80,
        model_used=None,
        fallback_used=False,
        analysis_mode='demo_sample',
        findings=[{
            'timestamp_seconds': 8.0,
            'timestamp': '00:08',
            'title': 'Demonstration sample observation',
            'severity': 'medium',
            'category': 'visual_consistency',
            'evidence': 'Illustrative sample record; no video file was uploaded or analyzed.',
            'explanation': 'This example demonstrates the video review display and is not an AI-generated finding.',
            'suggested_correction': 'Upload a video in an authenticated workspace to request real analysis.',
            'status': 'sample',
        }],
        created_at=now - timedelta(days=1),
        user_id=uid,
    ))

    db.flush()
    report_data = build_consistency_report(db, uid, [audit.id for audit in audits])
    report_data['demonstration_note'] = (
        'Demonstration-only consistency sample derived from the labeled rule-based sample audits; '
        'it is not an AI-generated report.'
    )
    db.add(ConsistencyReport(
        audit_ids=[audit.id for audit in audits],
        campaign_count=len(audits),
        report_data=report_data,
        created_at=now - timedelta(days=1),
        user_id=uid,
    ))
    db.add(ActivityEvent(
        event_type='Demo sample workspace initialized',
        description='Demonstration sample workspace initialized for the dedicated evaluator account.',
        related_entity_id=None,
        timestamp=now,
        user_id=uid,
    ))
    db.commit()
