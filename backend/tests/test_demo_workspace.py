@pytest.fixture
def api(
    monkeypatch: pytest.MonkeyPatch,
) -> Iterator[tuple[TestClient, dict[str, str], sessionmaker]]:
    monkeypatch.setenv('DEMO_ACCOUNT_EMAIL', 'evaluator@example.test')
    engine = create_engine('sqlite://', connect_args={'check_same_thread': False}, poolclass=StaticPool)
    Base.metadata.create_all(engine)
    test_session = sessionmaker(autocommit=False, autoflush=False, bind=engine)
    identity = {'uid': 'evaluator-user', 'email': 'evaluator@example.test'}
    app = FastAPI()
    for router in (
        profile_router,
        activity_router,
        approvals_router,
        assets_router,
        audits_router,
        consistency_router,
        guidelines_router,
        video_reviews_router,
    ):
        app.include_router(router)

    def override_db() -> Iterator[Session]:
        db = test_session()
        try:
            yield db
        finally:
            db.close()

    def override_identity() -> FirebaseIdentity:
        return FirebaseIdentity(
            uid=identity['uid'],
            email=identity['email'],
            display_name='Evaluator',
        )

    app.dependency_overrides[get_db] = override_db
    app.dependency_overrides[require_firebase_identity] = override_identity
    client = TestClient(app)
    try:
        yield client, identity, test_session
    finally:
        client.close()
        Base.metadata.drop_all(engine)
        engine.dispose()


def test_demo_profile_seeds_labeled_workspace_once(
    api: tuple[TestClient, dict[str, str], sessionmaker],
) -> None:
    client, _identity, test_session = api

    profile = client.get('/api/profile')
    assert profile.status_code == 200
    assert profile.json()['email'] == 'evaluator@example.test'

    audits = client.get('/api/audits').json()
    assert len(audits) == 2
    assert all(audit['campaign_name'].startswith('[DEMO SAMPLE]') for audit in audits)
    assert all(audit['analysis_mode'] == 'rules_only' for audit in audits)
    assert all('not generated by an AI model' in audit['findings'][0]['explanation'] for audit in audits)

    assets = client.get('/api/assets').json()
    assert len(assets) == 1
    assert 'DEMO SAMPLE - metadata only' in assets[0]['original_filename']
    assert assets[0]['file_size'] == 0

    video_reviews = client.get('/api/video-reviews').json()
    assert len(video_reviews) == 1
    assert video_reviews[0]['analysis_mode'] == 'demo_sample'
    assert video_reviews[0]['model_used'] is None
    assert 'not an AI-generated finding' in video_reviews[0]['findings'][0]['explanation']

    consistency_reports = client.get('/api/consistency-reports').json()
    assert len(consistency_reports) == 1
    assert 'Demonstration-only' in consistency_reports[0]['report_data']['demonstration_note']
    assert consistency_reports[0]['report_data']['recurring_violations']

    approvals = client.get('/api/approvals/workspace').json()
    assert len(approvals) == 2
    assert client.get('/api/activity').status_code == 200

    client.get('/api/profile')
    db = test_session()
    try:
        from backend.models import ActivityEvent, Asset, Audit, ConsistencyReport, VideoReview

        assert db.query(Audit).filter(Audit.user_id == 'evaluator-user').count() == 2
        assert db.query(Asset).filter(Asset.user_id == 'evaluator-user').count() == 1
        assert db.query(VideoReview).filter(VideoReview.user_id == 'evaluator-user').count() == 1
        assert db.query(ConsistencyReport).filter(ConsistencyReport.user_id == 'evaluator-user').count() == 1
        assert db.query(ActivityEvent).filter(ActivityEvent.user_id == 'evaluator-user').count() == 3
    finally:
        db.close()


